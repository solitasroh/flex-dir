namespace FlexDir.Core.Usage;

/// <summary>
/// 앱을 쓴 날을 남기는 포트. 원래는 도그푸딩 게이트(ADR-007)의 유일한 입력이었다.
/// <b>그 게이트는 폐기됐고 지금은 읽는 쪽이 없다</b> (ADR-007 §폐기 · 2026-08-07).
/// 기록은 그대로 남긴다 — "지난 달에 며칠 썼나" 는 나중에도 볼 수 있어야 한다.
///
/// <para>
/// <b>"사용" 은 사용자가 창을 요구한 순간이다.</b> 프로세스 수명도, 창이 떠 있던 시간도
/// 아니다. 상주 프로세스(ADR-003)라 둘 다 못 쓴다:
/// </para>
/// <list type="bullet">
///   <item>프로세스 수명으로 세면 로그인 후 계속 살아 있는 프로세스가 <b>7일 중 7일</b>을
///   만든다. 게이트가 항상 통과하면 아무것도 재지 않는 것이다.</item>
///   <item>창 표시 시간으로 세면 띄워 놓고 자리를 비운 시간이 사용량이 된다. 게다가
///   ADR-007 이 필요로 하는 숫자는 시간이 아니라 <b>며칠</b>이다.</item>
/// </list>
///
/// <para>
/// 그래서 남기는 것은 시각 하나뿐이고, 게이트는 그 시각들의 <b>서로 다른 날짜 수</b>를
/// 센다. 같은 날 여러 번은 하루다. 지속 시간을 기록하지 않는 이유도 같다 — 읽는 사람이
/// 없는 값이다.
/// </para>
///
/// <para>
/// 지금 이 포트를 부르는 곳은 <c>FlexDir.Host</c> 의 실행 시점과 활성화 요청(상주 중인
/// 프로세스에 두 번째 실행이 인자를 넘긴 순간)이다. 창이 생기면(phase B) 창 표시가 같은
/// 자리를 부른다 — 기록의 의미는 바뀌지 않는다.
/// </para>
/// </summary>
public interface IUsageLog
{
    /// <summary>
    /// 사용이 있었음을 남긴다. 하루에 여러 번 불릴 수 있다.
    /// <para>
    /// <b>실패해도 던지지 않는다.</b> 기록은 게이트의 입력일 뿐이고, 디스크가 말을 듣지
    /// 않는다고 앱이 뜨지 않으면 도그푸딩 자체가 불가능해진다. 그래서 호출자는 이 자리를
    /// <c>try</c> 로 감싸지 않는다 — 취소만 예외로 나온다.
    /// </para>
    /// </summary>
    /// <param name="at">사용 시각. 날짜 판정은 이 값의 오프셋 기준이다.</param>
    ValueTask RecordAsync(DateTimeOffset at, CancellationToken ct);
}
